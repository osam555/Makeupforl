/**
 * 검색어 허브.
 *
 * 100문100답은 문항 한 개가 짧아서 혼자서는 큰 검색어를 못 가져온다.
 * 사람들이 실제로 치는 말("혼주한복", "혼주머리")을 제목에 걸고, 그 아래
 * 관련 문항을 묶어 세우는 페이지가 따로 있어야 한다.
 *
 * 검색량은 네이버 검색광고 키워드도구 실측(2026-09-08)이다.
 *   혼주한복 16,450 / 혼주머리 5,790 / 혼주메이크업 5,060 /
 *   혼주올림머리 1,750 / 혼주헤어 810 / 혼주화장 320
 * '혼주화장'은 사실상 죽은 말이라 제목에 쓰지 않는다. 같은 뜻이면 '혼주메이크업'을 쓴다.
 *
 * 본문은 새로 지어낸 말이 아니라 원장이 문항에서 이미 답한 내용에서 나왔다.
 * 다만 답을 그대로 옮기지는 않는다. 100문100답은 유료로 열 예정이고(무료 5개),
 * 이 페이지가 그 답을 대신해 버리면 파는 물건이 없어진다.
 *
 * 그래서 절마다 "무엇이 문제인지"와 "왜 되돌리기 어려운지"까지만 쓴다.
 * 처방(어떤 피부 톤에 어떤 색, 뒤꽂이는 어떤 소재)은 문항과 상담에 남긴다.
 * 검색에서 이기려면 알맹이가 있어야 하고, 팔려면 남겨야 한다 — 그 경계가 여기다.
 */

export type HubSection = {
  /** 소제목 */
  h: string
  /** 본문 문단 */
  body: string[]
  /** 이 절의 근거가 되는 문항 slug */
  slugs: string[]
}

export type Hub = {
  /** 주소가 되는 말. 사람들이 실제로 검색하는 형태 그대로 쓴다 */
  slug: string
  /** 월간 검색량(네이버, PC+모바일) — 우선순위 판단 근거로 남긴다 */
  volume: number
  title: string
  description: string
  /** 제목 아래 한 문장 */
  lead: string
  /** 도입 문단 */
  intro: string[]
  sections: HubSection[]
  /** 함께 볼 갤러리 */
  gallery: { href: string; label: string }
  /** 메타 keywords 에 함께 실을 말 */
  keywords: string[]
}

